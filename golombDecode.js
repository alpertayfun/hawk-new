function decodePublicKey(
  y,
  n,
  low00, high00,
  low01, high01,
  publenBits,
  DecompressGR,
  DecodeInt
) {
  const lenBits = (arr) => arr.length;

  if (lenBits(y) !== publenBits) {
    return null;
  }

  const v = 16 - high00;

  const r00 = DecompressGR(y, n / 2, low00, high00);
  if (r00 === null) {
    return null;
  }

  let [q00, j] = r00;

  if (lenBits(y) < j + v) {
    return null;
  }

  q00[0] = (2 ** v) * q00[0] + DecodeInt(y.slice(j, j + v));

  j = j + v;

  while (j % 8 !== 0) {
    if (j >= lenBits(y) || y[j] !== 0) {
      return null;
    }
    j = j + 1;
  }

  q00[n / 2] = 0;

  for (let i = n / 2 + 1; i <= n - 1; i++) {
    q00[i] = -q00[n - i];
  }

  const r01 = DecompressGR(y.slice(j, lenBits(y)), n, low01, high01);
  if (r01 === null) {
    return null;
  }

  const [q01, jPrime] = r01;

  j = j + jPrime;

  while (j < lenBits(y)) {
    if (y[j] !== 0) {
      return null;
    }
    j = j + 1;
  }

  return [q00, q01];
}

